    private void iniciar() {
        Ui.estiloEncabezado(lblTitulo);
        Ui.configurarTabla(tblSoftware);
        modelo = (DefaultTableModel) tblSoftware.getModel();
        addComponentListener(new java.awt.event.ComponentAdapter() {
            @Override public void componentShown(java.awt.event.ComponentEvent e) { refrescar(); }
        });
        setSize(900, 560);
        setLocationRelativeTo(null);
        refrescar();
    }

    @Override
    public void refrescar() {
        if (modelo == null) return;
        String filtro = (String) cboTipo.getSelectedItem();
        List<Software> todos;
        try {
            todos = softwareDao.listar();
        } catch (Exception e) {
            Ui.fallo(this, "Error al cargar software: " + e.getMessage());
            return;
        }
        modelo.setRowCount(0);
        visibles.clear();
        for (Software s : todos) {
            if (TODO.equals(filtro) || s.getTipo().equals(filtro)) {
                visibles.add(s);
                modelo.addRow(new Object[] { s.getNombre(), s.getVersion(), s.getTipo(),
                        s.getLicencia(), s.getEstado() });
            }
        }
        lblTotal.setText(todos.isEmpty()
                ? "No hay software registrado. Use \"+ Registrar Software\" para agregar el primero."
                : visibles.size() + " software(s)");
    }

    private void registrar() {
        FrmSoftware.abrir(this, null);
        refrescar();
    }

    private void editar() {
        int fila = tblSoftware.getSelectedRow();
        if (fila < 0) { Ui.info(this, "Seleccione un software de la lista."); return; }
        FrmSoftware.abrir(this, visibles.get(tblSoftware.convertRowIndexToModel(fila)));
        refrescar();
    }

